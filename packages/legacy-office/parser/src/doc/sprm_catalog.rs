/// Whether [MS-DOC] 2.6 defines `opcode`.
pub(in crate::doc) fn is_defined(opcode: u16) -> bool {
    DEFINED.binary_search(&opcode).is_ok()
}

/// Skip a property whose opcode [MS-DOC] 2.6 does not define. Returns false
/// for a defined opcode, which the caller keeps handling as before.
pub(in crate::doc) fn skip_undefined(opcode: u16) -> bool {
    if is_defined(opcode) {
        return false;
    }
    crate::rejection::skipped("unknown Word property");
    true
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn catalog_is_sorted_and_knows_each_property_class() {
        assert!(DEFINED.windows(2).all(|pair| pair[0] < pair[1]));
        // sprmCFBold, sprmPJc80, sprmTJc90, sprmSBkc, sprmPicBrcTop80.
        for opcode in [0x0835, 0x2403, 0x5400, 0x3009, 0x6c02] {
            assert!(is_defined(opcode), "{opcode:#06x}");
        }
        crate::rejection::take_best_effort();
        assert!(!skip_undefined(0x0835));
        assert!(skip_undefined(0x0899));
        assert_eq!(
            crate::rejection::take_best_effort(),
            [(
                crate::rejection::BestEffort::Skipped,
                "unknown Word property"
            )]
        );
    }
}
