//! Stable legacy Office LCID resolution from [MS-LCID] 2.2 (2024-04-23).
//!
//! Microsoft locale names are preserved verbatim. They are not normalized as
//! RFC 5646: names such as `es-ES_tradnl` and alternate-sort suffixes carry
//! Microsoft-specific identity which a consumer may need to interpret.

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum Resolution {
    Assigned(&'static str),
    AssignedNonLanguageTag(&'static str),
    DocumentedAliases(&'static [&'static str]),
    Reserved(Option<&'static str>),
    CustomUserDefault,
    CustomUnspecified,
    Transient,
    Unassigned,
    Unknown,
}

pub(crate) fn resolve(value: u32) -> Resolution {
    use Resolution::*;
    match value {
        0x467 => return DocumentedAliases(&["ff-NG", "ff-Latn-NG"]),
        0x0c00 => return CustomUserDefault,
        0x1000 => return CustomUnspecified,
        0x2000 | 0x2400 | 0x2800 | 0x2c00 | 0x3000 | 0x3400 | 0x3800 | 0x3c00 | 0x4000 | 0x4400
        | 0x4800 | 0x4c00 => return Transient,
        0x007b | 0x007d | 0x0089 | 0x008a | 0x008b | 0x008d | 0x008e | 0x008f | 0x0090 | 0x0827
        | 0x2008 => return Unassigned,
        0x003d => return Reserved(Some("yi")),
        0x0058 => return Reserved(Some("mni")),
        0x0066 => return Reserved(Some("bin")),
        0x0069 => return Reserved(Some("ibb")),
        0x0071 => return Reserved(Some("kr")),
        0x0076 => return Reserved(Some("la")),
        0x0077 => return Reserved(Some("so")),
        0x0079 => return Reserved(Some("pap")),
        0x007f => return Reserved(None),
        0x0093 => return Reserved(Some("quc")),
        0x0458 => return Reserved(Some("mni-IN")),
        0x0459 => return Reserved(Some("sd-Deva-IN")),
        0x0466 => return Reserved(Some("bin-NG")),
        0x0469 => return Reserved(Some("ibb-NG")),
        0x0479 => return Reserved(Some("pap-029")),
        0x0486 => return Reserved(Some("qut-GT")),
        0x048d => return Reserved(Some("plt-MG")),
        0x048e => return Reserved(Some("zh-yue-HK")),
        0x048f => return Reserved(Some("tdd-Tale-CN")),
        0x0490 => return Reserved(Some("khb-Talu-CN")),
        0x0493 => return Reserved(Some("quc-CO")),
        0x0811 => return Reserved(Some("ja-Ploc-JP")),
        0x082c => return Reserved(Some("az-Cyrl-AZ")),
        0x083f => return Reserved(Some("kk-Latn-KZ")),
        0x0843 => return Reserved(Some("uz-Cyrl-UZ")),
        0x0850 => return Reserved(Some("mn-Mong-CN")),
        0x0851 => return Reserved(Some("bo-BT")),
        0x0c5f => return Reserved(Some("tmz-MA")),
        0x2409 => return Reserved(Some("en-029")),
        0x3809 => return Reserved(Some("en-ID")),
        0x4401 => return Reserved(Some("ar-Ploc-SA")),
        0x4801 => return Reserved(Some("ar-145")),
        0x5009 => return Reserved(Some("en-BH")),
        0x5409 => return Reserved(Some("en-EG")),
        0x5809 => return Reserved(Some("en-JO")),
        0x580a => return Reserved(Some("es-419")),
        0x5c09 => return Reserved(Some("en-KW")),
        0x6009 => return Reserved(Some("en-TR")),
        0x6409 => return Reserved(Some("en-YE")),
        0x783f => return Reserved(Some("kk-Cyrl")),
        0x7c3f => return Reserved(Some("kk-Latn")),
        0xf2ee | 0xeeee => return Reserved(None),
        0xe40c => return Reserved(Some("fr-015")),
        _ => {}
    }
    // Numeric table lookup avoids parsing or allocation on the per-property hot path.
    match ASSIGNED.binary_search_by_key(&value, |(lcid, _)| *lcid) {
        Ok(index) => {
            let name = ASSIGNED[index].1;
            if name.contains('_') {
                AssignedNonLanguageTag(name)
            } else {
                Assigned(name)
            }
        }
        Err(_) => Unknown,
    }
}

