#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn resolves_stable_default_and_alternate_names_verbatim() {
        assert_eq!(resolve(0x0409), Resolution::Assigned("en-US"));
        assert_eq!(
            resolve(0x040a),
            Resolution::AssignedNonLanguageTag("es-ES_tradnl")
        );
        assert_eq!(resolve(0x4c09), Resolution::Assigned("en-AE"));
        assert_eq!(
            resolve(0x0001_0407),
            Resolution::AssignedNonLanguageTag("de-DE_phoneb")
        );
        assert_eq!(
            resolve(0x0467),
            Resolution::DocumentedAliases(&["ff-NG", "ff-Latn-NG"])
        );
        assert_eq!(ASSIGNED.len(), 426);
        assert!(ASSIGNED.windows(2).all(|pair| pair[0].0 < pair[1].0));
        for &(lcid, tag) in ASSIGNED {
            let expected = if tag.contains('_') {
                Resolution::AssignedNonLanguageTag(tag)
            } else {
                Resolution::Assigned(tag)
            };
            assert_eq!(resolve(lcid), expected);
        }
    }
    #[test]
    fn never_guesses_contextual_reserved_or_unknown_values() {
        assert_eq!(resolve(0x0c00), Resolution::CustomUserDefault);
        assert_eq!(resolve(0x1000), Resolution::CustomUnspecified);
        assert_eq!(resolve(0x3000), Resolution::Transient);
        assert_eq!(resolve(0x007f), Resolution::Reserved(None));
        assert_eq!(resolve(0x0458), Resolution::Reserved(Some("mni-IN")));
        assert_eq!(resolve(0x0089), Resolution::Unassigned);
        assert_eq!(resolve(0x0400), Resolution::Unknown);
        assert_eq!(resolve(0xdead_beef), Resolution::Unknown);
    }
}
