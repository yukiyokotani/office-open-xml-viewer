#!/usr/bin/env node
// Generate packages/ooxml-common/src/spreadsheet_style_presets.generated.rs
// from ECMA-376 Part 1 Annex G presetTableStyles.xml: the built-in
// PivotTable styles (§18.8.40) as typed differential formats, deduplicated.
// Usage: node scripts/generate-spreadsheet-style-presets.mjs <presetTableStyles.xml>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) throw new Error('usage: generate-spreadsheet-style-presets.mjs <presetTableStyles.xml>');
const xml = readFileSync(source, 'utf8');

const attr = (tag, name) => {
  const match = new RegExp(`\\b${name}="([^"]*)"`).exec(tag);
  return match ? match[1] : null;
};
const color = (tag) => {
  if (!tag) return 'None';
  if (attr(tag, 'rgb') || attr(tag, 'indexed') || attr(tag, 'auto')) throw new Error(`unsupported color ${tag}`);
  const theme = attr(tag, 'theme');
  if (theme === null) throw new Error(`color without theme ${tag}`);
  const tint = attr(tag, 'tint');
  const tintText = tint === null ? 'None' : `Some(${Number(tint)}_f64)`;
  return `Some(PresetColor { theme: ${Number(theme)}, tint: ${tintText} })`;
};
const known = /^(dxf|font|b|color|fill|patternFill|fgColor|bgColor|border|left|right|top|bottom|horizontal|vertical)$/;

/** One `<dxf>` as a `PresetDxf` expression. */
function dxfExpr(dxf) {
  for (const [, name] of dxf.matchAll(/<\/?(\w+)/g)) {
    if (!known.test(name)) throw new Error(`unsupported dxf element ${name} in ${dxf}`);
  }
  const font = /<font>([\s\S]*?)<\/font>/.exec(dxf);
  const fontExpr = font
    ? `Some(PresetFont { bold: ${/<b\/>/.test(font[1])}, color: ${color(/<color [^>]*\/>/.exec(font[1])?.[0])} })`
    : 'None';
  const pattern = /<patternFill([^>]*)>([\s\S]*?)<\/patternFill>/.exec(dxf);
  const fillExpr = pattern
    ? `Some(PresetFill { pattern_type: ${JSON.stringify(attr(pattern[1], 'patternType') ?? 'solid')}, fg: ${color(/<fgColor [^>]*\/>/.exec(pattern[2])?.[0])}, bg: ${color(/<bgColor [^>]*\/>/.exec(pattern[2])?.[0])} })`
    : 'None';
  if (/<fill>/.test(dxf) && !pattern) throw new Error(`unsupported fill ${dxf}`);
  const border = /<border>([\s\S]*?)<\/border>/.exec(dxf);
  let borderExpr = 'None';
  if (border) {
    const edges = {};
    for (const [, name, attrs, body] of border[1].matchAll(/<(\w+)([^>]*?)(?:\/>|>([\s\S]*?)<\/\1>)/g)) {
      const style = attr(attrs, 'style');
      edges[name] = `Some(PresetEdge { style: ${style === null ? 'None' : `Some(${JSON.stringify(style)})`}, color: ${color(body && /<color [^>]*\/>/.exec(body)?.[0])} })`;
    }
    const edge = (name) => edges[name] ?? 'None';
    borderExpr = `Some(PresetBorder { left: ${edge('left')}, right: ${edge('right')}, top: ${edge('top')}, bottom: ${edge('bottom')}, horizontal: ${edge('horizontal')}, vertical: ${edge('vertical')} })`;
  }
  return `PresetDxf { font: ${fontExpr}, fill: ${fillExpr}, border: ${borderExpr} }`;
}

const blocks = [...xml.matchAll(/<(PivotStyle(?:Light|Medium|Dark)\d+)>([\s\S]*?)<\/\1>/g)];
const dxfIds = new Map();
const styles = [];
for (const [, name, raw] of blocks) {
  const body = raw.trim().replace(/>\s+</g, '><');
  const local = [...body.matchAll(/<dxf>[\s\S]*?<\/dxf>/g)].map(([dxf]) => {
    const expr = dxfExpr(dxf);
    if (!dxfIds.has(expr)) dxfIds.set(expr, dxfIds.size);
    return dxfIds.get(expr);
  });
  const elements = [...body.matchAll(/<tableStyleElement type="(\w+)"(?: size="(\d+)")? dxfId="(\d+)"\/>/g)]
    .map(([, type, size, id]) => [type, Number(size ?? 1), local[Number(id)]]);
  if (elements.length === 0) throw new Error(`${name} has no elements`);
  styles.push([name, elements]);
}
let out = `// Built-in PivotTable styles of ECMA-376 Part 1 Annex G
// (presetTableStyles.xml), deduplicated. Generated by
// scripts/generate-spreadsheet-style-presets.mjs; do not edit.

/// Differential formats referenced by the styles below.
static PIVOT_DXFS: [PresetDxf; ${dxfIds.size}] = [\n`;
for (const expr of dxfIds.keys()) out += `    ${expr},\n`;
out += `];\n\n/// (style name, [(element type, band size, PIVOT_DXFS index)]).
static PIVOT_STYLES: [PresetStyleEntry; ${styles.length}] = [\n`;
for (const [name, elements] of styles) {
  out += `    (${JSON.stringify(name)}, &[${elements.map(([t, s, d]) => `(${JSON.stringify(t)}, ${s}, ${d})`).join(', ')}]),\n`;
}
out += '];\n';
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(resolve(here, '../packages/ooxml-common/src/spreadsheet_style_presets.generated.rs'), out);
console.log(`${styles.length} styles, ${dxfIds.size} dxfs`);
