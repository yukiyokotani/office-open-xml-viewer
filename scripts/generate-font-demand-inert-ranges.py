#!/usr/bin/env python3
"""Generate opt-in normalization-inert assigned ranges, and the canonical
decompositions and cluster joiners of the other assigned scalars, from pinned
UnicodeData.
Input: https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt
No renderer normalization/shaping/catalogue implementation is used or generated.
"""
import argparse, hashlib
from pathlib import Path

INPUT_SHA256 = '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c'
p = argparse.ArgumentParser()
p.add_argument('--unicode-data', type=Path, required=True)
p.add_argument('--check', action='store_true')
args = p.parse_args()
raw = args.unicode_data.read_bytes()
if hashlib.sha256(raw).hexdigest() != INPUT_SHA256:
    raise SystemExit('expected pinned Unicode 17.0.0 UnicodeData.txt hash')
assigned, excluded = set(), set()
decompositions, joiners = {}, set()
first = None
for line in raw.decode('utf-8').splitlines():
    row = line.split(';')
    cp, name = int(row[0], 16), row[1]
    if name.endswith(', First>'):
        first = cp
    elif name.endswith(', Last>'):
        assert first is not None
        assigned.update(range(first, cp + 1)); first = None
    else:
        assigned.add(cp)
    if int(row[3]):
        excluded.add(cp)
        joiners.add(cp)
    decomposition = row[5]
    if decomposition and not decomposition.startswith('<'):
        excluded.add(cp)
        parts = [int(part, 16) for part in decomposition.split()]
        decompositions[cp] = parts
        # All canonical pairs conservatively include composition-excluded pairs.
        if len(parts) == 2:
            excluded.add(parts[1])
            joiners.add(parts[1])
assert first is None
# UAX15/Unicode Standard 3.12 algorithmic decomposition and composition domains.
for lo, hi in [(0x1100,0x1112),(0x1161,0x1175),(0x11a8,0x11c2),(0xac00,0xd7a3),(0xd800,0xdfff)]:
    excluded.update(range(lo, hi + 1))
ranges = []
for cp in sorted(assigned - excluded):
    if ranges and ranges[-1][1] + 1 == cp:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])
text = '''/** Generated by scripts/generate-font-demand-inert-ranges.py.
 * Unicode 17.0.0 assigned scalars excluding canonical decomposition keys,
 * canonical-pair second operands, nonzero CCC and algorithmic Hangul domains.
 * UnicodeData.txt SHA-256: ''' + INPUT_SHA256 + '''
 * https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt
 * UAX15 §12.1 normalization stability applies to assigned strings. Unassigned
 * scalars are intentionally unknown. This proves spelling only, never support.
 * Analysis is invoked only for opt-in demand; flattened worker assets may
 * include these proof bytes even when no font source is configured.
 */
let ranges: readonly number[] | undefined;
/** Flattened consumer workers still include these bytes; first use, not module
 * evaluation, allocates the table. Parsing without font sources never invokes it. */
export function fontDemandInertRanges(): readonly number[] {
  return ranges ??= [
''' + ''.join(f'  0x{lo:x}, 0x{hi:x},\n' for lo, hi in ranges) + '  ];\n}\n'
out = Path(__file__).resolve().parents[1] / 'packages/core/src/fonts/inert-scalar-ranges.ts'

DIGITS = '0123456789abcdefghijklmnopqrstuvwxyz'
def b36(n):
    text = ''
    while True:
        n, digit = divmod(n, 36)
        text = DIGITS[digit] + text
        if not n:
            return text
# Hangul vowels and trailing consonants join a cluster too (algorithmic pairs).
joiners.update(range(0x1161, 0x1176))
joiners.update(range(0x11a8, 0x11c3))
entries, previous = [], 0
for cp in sorted(decompositions):
    entries.append(b36(cp - previous) + ':' + ','.join(b36(part) for part in decompositions[cp]))
    previous = cp
joiner_ranges = []
for cp in sorted(joiners):
    if joiner_ranges and joiner_ranges[-1][1] + 1 == cp:
        joiner_ranges[-1][1] = cp
    else:
        joiner_ranges.append([cp, cp])
spans, previous = [], 0
for lo, hi in joiner_ranges:
    spans.append(b36(lo - previous) + ('' if hi == lo else '-' + b36(hi - lo)))
    previous = hi
decomposition_text = '''/** Generated by scripts/generate-font-demand-inert-ranges.py.
 * Unicode 17.0.0 canonical decompositions (one level; Hangul syllables are
 * algorithmic and not listed) and cluster joiners: nonzero CCC, the second
 * operand of a canonical pair, and the Hangul vowel and trailing jamo.
 * UnicodeData.txt SHA-256: ''' + INPUT_SHA256 + '''
 * https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt
 * Encoding: `;`-separated `Δcp:part[,part]` (base 36, Δ from the previous
 * key) and `,`-separated joiner spans `Δlo[-len]` (base 36, Δ from the
 * previous span's end). Decoded on first use.
 */
export const CANONICAL_DECOMPOSITIONS =
  ''' + repr(';'.join(entries)) + ''';
export const CLUSTER_JOINERS = ''' + repr(','.join(spans)) + ''';
'''
decomposition_out = out.with_name('canonical-decompositions.ts')
if args.check:
    if out.read_text() != text:
        raise SystemExit('font demand inert ranges are stale')
    if decomposition_out.read_text() != decomposition_text:
        raise SystemExit('font demand canonical decompositions are stale')
else:
    out.write_text(text)
    decomposition_out.write_text(decomposition_text)
print(f'{len(ranges)} pinned assigned-inert ranges, {len(entries)} canonical decompositions, {len(joiner_ranges)} joiner spans')
