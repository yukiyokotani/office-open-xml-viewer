#!/usr/bin/env node
// Generate packages/xlsx/parser/src/pivot_presets.rs from ECMA-376 Part 1
// Annex G presetTableStyles.xml (the built-in PivotTable styles, §18.8.40).
// Usage: node scripts/generate-pivot-style-presets.mjs <presetTableStyles.xml>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) throw new Error('usage: generate-pivot-style-presets.mjs <presetTableStyles.xml>');
const xml = readFileSync(source, 'utf8');
const blocks = [...xml.matchAll(/<(PivotStyle(?:Light|Medium|Dark)\d+)>([\s\S]*?)<\/\1>/g)];
const dxfIds = new Map();
const styles = [];
for (const [, name, raw] of blocks) {
  const body = raw.trim().replace(/>\s+</g, '><');
  const local = [...body.matchAll(/<dxf>[\s\S]*?<\/dxf>/g)].map(([dxf]) => {
    if (!dxfIds.has(dxf)) dxfIds.set(dxf, dxfIds.size);
    return dxfIds.get(dxf);
  });
  const elements = [...body.matchAll(/<tableStyleElement type="(\w+)"(?: size="(\d+)")? dxfId="(\d+)"\/>/g)]
    .map(([, type, size, id]) => [type, Number(size ?? 1), local[Number(id)]]);
  if (elements.length === 0) throw new Error(`${name} has no elements`);
  styles.push([name, elements]);
}
const quote = (value) => JSON.stringify(value);
let out = `//! Built-in PivotTable styles of ECMA-376 Part 1 Annex G
//! (presetTableStyles.xml), deduplicated. Generated by
//! scripts/generate-pivot-style-presets.mjs; do not edit.

/// Differential formats referenced by the styles below.
pub(crate) const DXFS: [&str; ${dxfIds.size}] = [\n`;
for (const dxf of dxfIds.keys()) out += `    ${quote(dxf)},\n`;
out += `];\n\n/// (style name, [(element type, band size, DXFS index)]).
pub(crate) const STYLES: [(&str, &[(&str, u32, u16)]); ${styles.length}] = [\n`;
for (const [name, elements] of styles) {
  out += `    (${quote(name)}, &[${elements.map(([t, s, d]) => `(${quote(t)}, ${s}, ${d})`).join(', ')}]),\n`;
}
out += '];\n';
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(resolve(here, '../packages/xlsx/parser/src/pivot_presets.rs'), out);
console.log(`${styles.length} styles, ${dxfIds.size} dxfs`);
