#!/usr/bin/env node
// Run after the release's root version bump. CI and publishing check without
// --write, so neither an omitted bump nor an accidentally widened peer can ship.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const read = path => JSON.parse(readFileSync(new URL(path, root), 'utf8'));
const { version } = read('package.json');
// Every exact-version companion package of @silurus/ooxml.
const companions = ['packages/legacy-office/package.json', 'packages/opendocument/package.json'];
const versionPath = new URL('src/companion-version.ts', root);
const source = `// Generated by pnpm sync:versions; checked in CI and before publishing.\nexport const COMPANION_VERSION = '${version}';\n`;
if (process.argv.includes('--write')) {
  for (const path of companions) {
    const companion = read(path);
    companion.version = version;
    companion.peerDependencies['@silurus/ooxml'] = version;
    writeFileSync(new URL(path, root), JSON.stringify(companion, null, 2) + '\n');
  }
  writeFileSync(versionPath, source);
} else {
  const stale = companions.some((path) => {
    const companion = read(path);
    return companion.version !== version || companion.peerDependencies['@silurus/ooxml'] !== version;
  });
  if (stale || readFileSync(versionPath, 'utf8') !== source) {
    throw new Error('Companion version/peer/runtime pin differs from root; run pnpm sync:versions');
  }
}
console.log(`Companion lockstep verified: ${version}`);
