#!/usr/bin/env node
// Generates packages/pptx/src/office-face-weight-index.generated.ts from the
// reference font-metrics catalogue (the generated Office/macOS bundle JSON plus
// the pinned open-font profiles), the same profiles `findReferenceFontMetrics`
// serves.
//
// `officeFaceWeight` (packages/pptx/src/office-face-weight.ts) needs only one
// fact per catalogue name and style: whether every profile under that name has
// the same weight, and which. For such a name the face weight is that weight
// for both regular and bold requests; for any other name it is the requested
// weight. The index records exactly those names, so the PPTX font-demand path
// does not have to bundle the whole metrics table.
//
// Usage (from the repository root):
//   node scripts/generate-pptx-face-weight-index.mjs          # rewrite the file
//   node scripts/generate-pptx-face-weight-index.mjs --check  # fail if stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { OPEN_FONT_REFERENCE_PROFILES } from '../packages/core/src/fonts/reference-font-metrics-open.ts';
import { normalizeReferenceFontFamilyName } from '../packages/core/src/fonts/reference-font-name.ts';

const root = new URL('..', import.meta.url);
const DATA = new URL('packages/core/src/fonts/reference-font-metrics-data.json', root);
export const OUTPUT = fileURLToPath(new URL('packages/pptx/src/office-face-weight-index.generated.ts', root));

const STYLE_CODES = { normal: 'n', italic: 'i' };

/** Weights per `${styleCode}${normalized alias}`, as the alias index buckets them. */
function weightsByName(profiles) {
  const weights = new Map();
  for (const profile of profiles) {
    const code = STYLE_CODES[profile.style];
    if (code === undefined) throw new Error(`unknown style ${profile.style} for ${profile.family}`);
    if (!Number.isInteger(profile.weight)) throw new Error(`non-integer weight for ${profile.family}`);
    for (const alias of new Set(profile.aliases.map(normalizeReferenceFontFamilyName))) {
      if (!alias) continue; // an empty query never matches (findReferenceFontMetrics)
      if (alias.includes('|')) throw new Error(`alias ${JSON.stringify(alias)} contains a separator`);
      const key = `${code}${alias}`;
      const set = weights.get(key);
      if (set === undefined) weights.set(key, new Set([profile.weight]));
      else set.add(profile.weight);
    }
  }
  return weights;
}

export function buildOfficeFaceWeightIndexSource() {
  const data = JSON.parse(readFileSync(DATA, 'utf8'));
  const groups = new Map();
  for (const [key, weights] of weightsByName([...data.profiles, ...OPEN_FONT_REFERENCE_PROFILES])) {
    if (weights.size !== 1) continue;
    const group = `${key[0]}${[...weights][0]}`;
    const names = groups.get(group);
    if (names === undefined) groups.set(group, [key.slice(1)]);
    else names.push(key.slice(1));
  }
  const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
  const lines = [...groups.keys()].sort(compare)
    .map((group) => [group, ...groups.get(group).sort(compare)].join('|'));
  return `// Generated by scripts/generate-pptx-face-weight-index.mjs from the reference
// font-metrics catalogue (packages/core/src/fonts/reference-font-metrics-data.json
// and reference-font-metrics-open.ts). Do not edit; rerun the generator.
//
// One entry per style and weight: a style code (n = normal, i = italic) and the
// weight, then every normalized catalogue name whose profiles of that style all
// have that single weight, separated by "|".
export const OFFICE_SINGLE_WEIGHT_FACES: readonly string[] = [
${lines.map((line) => `  ${JSON.stringify(line)},`).join('\n')}
];
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const source = buildOfficeFaceWeightIndexSource();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUTPUT, 'utf8') !== source) {
      console.error(`${OUTPUT} is stale; run node scripts/generate-pptx-face-weight-index.mjs`);
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, source);
  }
}
